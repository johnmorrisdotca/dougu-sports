// Fetches the Material Symbols the emblems use from Google's official repository at a pinned commit and writes them to src/emblems/emblem.material.data.ts, so the package carries the
// paths and has no runtime dependency. Material Symbols are licensed under the Apache License 2.0 (see NOTICE.md). Run `node scripts/fetch-material-symbols.mjs` to refetch; to move to a
// newer release, change COMMIT, run it, look at a contact sheet (`node scripts/emblem-sheet.mjs sheet.png`) and commit the new data.
import { writeFileSync } from "node:fs";
import process from "node:process";

/** The commit of google/material-design-icons the paths come from. */
const COMMIT = "49d4db35df873165d6bd6ba09b063c7dafbac2f4";
const BASE = `https://raw.githubusercontent.com/google/material-design-icons/${COMMIT}/symbols/web`;
/** The icons: the constant's name, and the icon's name in the repository. Each is fetched outlined (the line style) and filled (the metal style). */
const ICONS = [
  ["EMOJI_EVENTS", "emoji_events"],
  ["MILITARY_TECH", "military_tech"],
  ["WORKSPACE_PREMIUM", "workspace_premium"],
  ["CROWN", "crown"],
  ["STAR", "star"],
  ["SHIELD", "shield"],
  ["SPORTS_FOOTBALL", "sports_football"],
  ["SPORTS_HOCKEY", "sports_hockey"],
  ["SPORTS_BASKETBALL", "sports_basketball"],
  ["SPORTS_BASEBALL", "sports_baseball"],
  ["SPORTS_SOCCER", "sports_soccer"],
  ["SPORTS_TENNIS", "sports_tennis"],
  ["SPORTS_VOLLEYBALL", "sports_volleyball"],
  ["SPORTS_CRICKET", "sports_cricket"],
  ["SPORTS_RUGBY", "sports_rugby"],
  ["SPORTS_HANDBALL", "sports_handball"],
];

/** The path data of one icon file; the files are one `<path>` in a 960 box. */
async function pathOf(name, fill) {
  const url = `${BASE}/${name}/materialsymbolsoutlined/${name}${fill ? "_fill1" : ""}_24px.svg`;
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${response.status} for ${url}`);
  const svg = await response.text();
  const paths = [...svg.matchAll(/<path d="([^"]+)"/g)].map((m) => m[1]);
  if (paths.length !== 1 || !svg.includes('viewBox="0 -960 960 960"')) throw new Error(`${url} is not one path in a 960 box`);
  return paths[0];
}

let out = `// Generated by scripts/fetch-material-symbols.mjs: do not edit by hand.
// Material Symbols by Google, from google/material-design-icons at ${COMMIT}, under the Apache License 2.0 (NOTICE.md).
// Each icon is [outlined, filled]: the paths of a 960 by 960 box whose top is at -960 (viewBox "0 -960 960 960").

/** The commit of google/material-design-icons these paths come from. */
export const MATERIAL_COMMIT = "${COMMIT}";
`;
for (const [constant, name] of ICONS) {
  const [outlined, filled] = await Promise.all([pathOf(name, false), pathOf(name, true)]);
  out += `\n/** Material Symbols \`${name}\`. */\nexport const M_${constant}: readonly [string, string] = [\n  "${outlined}",\n  "${filled}",\n];\n`;
}
writeFileSync(new URL("../src/emblems/emblem.material.data.ts", import.meta.url), out);
process.stdout.write(`wrote ${ICONS.length} icons from ${COMMIT}\n`);
